const std = @import("std");
const utils = @import("utils");
const clap = @import("clap");

fn typeName(
    allocator: std.mem.Allocator,
    node: std.json.Value,
    zig: bool,
) anyerror![]const u8 {
    if (node.object.get("$ref")) |ref| {
        const name = (switch (ref) {
            .string => |text| text,
            else => return error.ExpectedString,
        });
        const separator = std.mem.lastIndexOfScalar(u8, name, '/') orelse {
            return error.InvalidReference;
        };
        return name[separator + 1 ..];
    }
    if (node.object.get("enum")) |choices| {
        var items: std.array_list.Managed([]const u8) = .init(allocator);
        for (choices.array.items) |choice| try items.append(
            if (zig) (switch (choice) {
                .string => |text| text,
                else => return error.ExpectedString,
            }) else try std.json.Stringify.valueAlloc(
                allocator,
                choice,
                .{ .whitespace = .indent_2 },
            ),
        );
        const names = try std.mem.join(
            allocator,
            if (zig) ", " else " | ",
            items.items,
        );
        return if (zig) allocator.print("enum {{ {s} }}", .{names}) else names;
    }
    const kind = (switch ((switch (node) {
        .object => |object| object.get("type") orelse return error.MissingField,
        else => return error.ExpectedObject,
    })) {
        .string => |text| text,
        else => return error.ExpectedString,
    });
    if (std.mem.eql(u8, kind, "array")) {
        const item = try typeName(
            allocator,
            (switch (node) {
                .object => |object| object.get("items") orelse return error.MissingField,
                else => return error.ExpectedObject,
            }),
            zig,
        );
        return if (zig) allocator.print("[]const {s}", .{item}) else allocator.print(
            "Array<{s}>",
            .{item},
        );
    }
    if (std.mem.eql(u8, kind, "string"))
        return if (zig) "[]const u8" else "string";
    if (std.mem.eql(u8, kind, "boolean"))
        return if (zig) "bool" else "boolean";
    if (std.mem.eql(u8, kind, "integer")) {
        if (!zig)
            return "number";
        return if (node.object.get("x-zig-type")) |t| (switch (t) {
            .string => |text| text,
            else => return error.ExpectedString,
        }) else "u64";
    }
    return error.UnsupportedSchemaType;
}

const params = clap.parseParamsComptime(
    \\-h, --help  Display this help and exit.
    \\--check  Check without changing files.
);

/// Generates Zig, TypeScript, JavaScript and schema bindings from the protocol contract.
/// Parses subcommand arguments; --check reports drift without rewriting generated files.
pub fn generate(
    allocator: std.mem.Allocator,
    io: std.Io,
    environ: *std.process.Environ.Map,
    argv: []const []const u8,
) !void {
    var iter: clap.args.SliceIterator = .{ .args = argv };
    var diagnostic: clap.Diagnostic = .{};
    var parsed = clap.parseEx(clap.Help, &params, clap.parsers.default, &iter, .{
        .allocator = allocator,
        .diagnostic = &diagnostic,
    }) catch |err| {
        std.log.err("Command line: {t}; argument: {s}", .{ err, diagnostic.arg });
        return err;
    };
    defer parsed.deinit();
    if (parsed.args.help != 0) {
        try std.Io.File.stdout().writeStreamingAll(io, "Usage: pizza-tools proto [options]\n");
        return clap.helpToFile(io, .stdout(), clap.Help, &params, .{});
    }
    const schema = try std.json.parseFromSliceLeaky(
        std.json.Value,
        allocator,
        try std.Io.Dir.cwd().readFileAlloc(
            io,
            "core/proto/contract.json",
            allocator,
            .limited(128 * 1024 * 1024),
        ),
        .{ .allocate = .alloc_always },
    );
    const config = (switch (schema) {
        .object => |object| object.get("x-pizza") orelse return error.MissingField,
        else => return error.ExpectedObject,
    });
    var zig: std.Io.Writer.Allocating = .init(allocator);
    var ts: std.Io.Writer.Allocating = .init(allocator);
    const zw = &zig.writer;
    const tw = &ts.writer;
    const comment = "// Generated by zig build proto; edit contract.json.\n";
    try zw.writeAll(comment);
    try tw.writeAll(comment);
    try zw.print(
        "pub const api_version: u16 = {d};\npub const bridge_channel = {s};\n" ++
            "pub const journal_magic: u32 = 0x{x:0>8};\n" ++
            "pub const journal_header_bytes: usize = {d};\n",
        .{
            try utils.json.unsigned((switch (config) {
                .object => |object| object.get("version") orelse return error.MissingField,
                else => return error.ExpectedObject,
            })),
            try std.json.Stringify.valueAlloc(
                allocator,
                (switch (config) {
                    .object => |object| object.get("bridge_channel") orelse return error.MissingField,
                    else => return error.ExpectedObject,
                }),
                .{ .whitespace = .indent_2 },
            ),
            try utils.json.unsigned(
                (switch (config) {
                    .object => |object| object.get("journal_magic") orelse return error.MissingField,
                    else => return error.ExpectedObject,
                }),
            ),
            try utils.json.unsigned(
                (switch (config) {
                    .object => |object| object.get("journal_header_bytes") orelse return error.MissingField,
                    else => return error.ExpectedObject,
                }),
            ),
        },
    );
    try zw.writeAll("pub const BridgeMethod = enum { ");
    try tw.writeAll("export type BridgeMethod = ");
    const methods = config.object.get("bridge_methods") orelse return error.MissingField;
    for (methods.array.items, 0..) |method, index| {
        try zw.print("{s}, ", .{method.string});
        if (index != 0) try tw.writeAll(" | ");
        try tw.writeAll(try std.json.Stringify.valueAlloc(allocator, method, .{}));
    }
    try zw.writeAll("};\n");
    try tw.writeAll(";\n");
    try zw.writeAll("pub const JournalPhase = enum(u8) { ");
    var phases = ((switch (config) {
        .object => |object| object.get("journal_phases") orelse return error.MissingField,
        else => return error.ExpectedObject,
    })).object.iterator();
    while (phases.next()) |entry| try zw.print(
        "{s} = {d}, ",
        .{
            entry.key_ptr.*,
            try utils.json.unsigned(entry.value_ptr.*),
        },
    );
    try zw.writeAll(
        "};\npub const journal_offsets = struct {\n",
    );
    var offsets = ((switch (config) {
        .object => |object| object.get("journal_offsets") orelse return error.MissingField,
        else => return error.ExpectedObject,
    })).object.iterator();
    while (offsets.next()) |entry| try zw.print(
        "pub const {s}: usize = {d};\n",
        .{
            entry.key_ptr.*,
            try utils.json.unsigned(entry.value_ptr.*),
        },
    );
    try zw.writeAll("};\n");
    var definitions = ((switch (schema) {
        .object => |object| object.get("$defs") orelse return error.MissingField,
        else => return error.ExpectedObject,
    })).object.iterator();
    while (definitions.next()) |entry| {
        const name = entry.key_ptr.*;
        const node = entry.value_ptr.*;
        if (std.mem.eql(u8, (switch ((switch (node) {
            .object => |object| object.get("type") orelse return error.MissingField,
            else => return error.ExpectedObject,
        })) {
            .string => |text| text,
            else => return error.ExpectedString,
        }), "object")) {
            try zw.print("pub const {s} = struct {{\n", .{name});
            try tw.print("export interface {s} {{\n", .{name});
            var properties = ((switch (node) {
                .object => |object| object.get("properties") orelse return error.MissingField,
                else => return error.ExpectedObject,
            })).object.iterator();
            while (properties.next()) |property| {
                try zw.print(
                    "{s}: {s},\n",
                    .{
                        property.key_ptr.*,
                        try typeName(allocator, property.value_ptr.*, true),
                    },
                );
                try tw.print(
                    "{s}: {s};\n",
                    .{
                        property.key_ptr.*,
                        try typeName(allocator, property.value_ptr.*, false),
                    },
                );
            }
            try zw.writeAll("};\n");
            try tw.writeAll("}\n");
        } else {
            try zw.print(
                "pub const {s} = {s};\n",
                .{ name, try typeName(allocator, node, true) },
            );
            try tw.print(
                "export type {s} = {s};\n",
                .{ name, try typeName(allocator, node, false) },
            );
        }
    }
    const temporary = try utils.filesystem.createTemporaryDirectory(allocator, io, "pizza-proto-");
    defer std.Io.Dir.cwd().deleteTree(io, temporary) catch |err| std.log.warn("Cleanup {s}: {t}", .{ temporary, err });
    const zig_file = try std.fs.path.join(
        allocator,
        &.{ temporary, "generated.zig" },
    );
    try std.Io.Dir.cwd().writeFile(io, .{
        .sub_path = zig_file,
        .data = zig.written(),
    });
    _ = try utils.process.checkedOutput(
        allocator,
        io,
        environ,
        &.{ environ.get("ZIG") orelse "zig", "fmt", zig_file },
    );
    var outputs = std.json.Value{ .object = .{} };
    try outputs.object.put(
        allocator,
        "ui/execution/gui/src/generated/proto.d.ts",
        std.json.Value{ .string = ts.written() },
    );
    try outputs.object.put(
        allocator,
        "ui/execution/gui/src/generated/contract.js",
        std.json.Value{
            .string = try allocator.print(
                "{s}export const contract = {s};\nexport const api = contract[\"x-pizza\"];\n",
                .{
                    comment,
                    try std.json.Stringify.valueAlloc(
                        allocator,
                        schema,
                        .{ .whitespace = .indent_2 },
                    ),
                },
            ),
        },
    );
    try outputs.object.put(
        allocator,
        "ui/execution/gui/src/generated/contract.schema.json",
        std.json.Value{
            .string = try allocator.print(
                "{s}\n",
                .{
                    try std.json.Stringify.valueAlloc(
                        allocator,
                        schema,
                        .{ .whitespace = .indent_2 },
                    ),
                },
            ),
        },
    );
    const input_file = try std.fs.path.join(allocator, &.{ temporary, "web.json" });
    try std.Io.Dir.cwd().writeFile(io, .{
        .sub_path = input_file,
        .data = try std.json.Stringify.valueAlloc(
            allocator,
            outputs,
            .{ .whitespace = .indent_2 },
        ),
    });
    outputs = try std.json.parseFromSliceLeaky(
        std.json.Value,
        allocator,
        try utils.process.checkedOutput(
            allocator,
            io,
            environ,
            &.{
                (environ.get("NODE") orelse "node"),
                "tools/format_web.mjs",
                input_file,
            },
        ),
        .{ .allocate = .alloc_always },
    );
    try outputs.object.put(
        allocator,
        "core/proto/generated.zig",
        std.json.Value{
            .string = try std.Io.Dir.cwd().readFileAlloc(
                io,
                zig_file,
                allocator,
                .limited(128 * 1024 * 1024),
            ),
        },
    );
    var files = outputs.object.iterator();
    var stale = false;
    while (files.next()) |entry| {
        const content = (switch (entry.value_ptr.*) {
            .string => |text| text,
            else => return error.ExpectedString,
        });
        if (parsed.args.check != 0) {
            const current = std.Io.Dir.cwd().readFileAlloc(
                io,
                entry.key_ptr.*,
                allocator,
                .limited(128 * 1024 * 1024),
            ) catch "";
            if (!std.mem.eql(u8, current, content)) {
                std.log.err(
                    "Generated protocol drift: {s}; run zig build proto",
                    .{entry.key_ptr.*},
                );
                stale = true;
            }
        } else {
            if (std.fs.path.dirname(entry.key_ptr.*)) |parent|
                try std.Io.Dir.cwd().createDirPath(io, parent);
            try std.Io.Dir.cwd().writeFile(io, .{
                .sub_path = entry.key_ptr.*,
                .data = content,
            });
        }
    }
    if (stale)
        return error.ProtocolDrift;
}
